    private static Technology tech(String id,String prerequisites,String packs,int count,double sec,String unlocks) {
        Map<String,Integer> p=new LinkedHashMap<>();for(String pack:packs.split(","))p.put(M+pack+"_science_pack",1);
        return new Technology(id,prerequisites.isEmpty()?List.of():List.of(prerequisites.split(",")),p,count,Units.ticks(sec),unlocks.isEmpty()?List.of():List.of(unlocks.split(",")));
    }
