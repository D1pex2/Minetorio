    private static final String M="minetorio:";
    private static final List<OilRecipe> RECIPES=buildMixed();
    private OilData() {}
    public static List<OilRecipe> recipes() { return RECIPES; }
    public static OilRecipe recipe(String id) { return RECIPES.stream().filter(r->r.id().equals(id)).findFirst().orElse(null); }
    private static List<Ingredient> items(String csv) {
        if(csv.isBlank()) return List.of();
        return Arrays.stream(csv.split(",")).map(String::trim).map(s->{var p=s.split(" ",2);String id=p[1];return new Ingredient(id.contains(":")?id:M+id,Integer.parseInt(p[0]));}).toList();
    }
    private static Map<String,Double> fluids(String csv) {
        Map<String,Double> map=new LinkedHashMap<>();
        if(!csv.isBlank()) for(String s:csv.split(",")) {var p=s.trim().split(" ",2);map.put(p[1],Double.parseDouble(p[0]));}
        return map;
    }
    private static OilRecipe mixed(String id,MachineKind kind,double sec,String itemIn,String fluidIn,String itemOut,String fluidOut) {
        return new OilRecipe(id,items(itemIn),items(itemOut),fluids(fluidIn),fluids(fluidOut),Units.ticks(sec),kind);
    }
